LAYOUT = StateLayout([StateVariable("a", 2), StateVariable("b", 1)])
KEYS = (DataKey("0", "WOPR:P1"), DataKey("1", "WOPR:P1"), DataKey("1", "WBHP:P1"))
#: The true affine map: outputs = MATRIX @ [a; b] + OFFSET.
MATRIX = np.array([[1.0, -2.0, 0.5], [0.0, 3.0, 1.0], [4.0, 0.0, -1.0]])
OFFSET = np.array([10.0, -1.0, 200.0])


class _Affine:
    """An affine least-squares map (test only): outputs = W [x; 1]."""

    version = "1"

    def __init__(self, ridge: float = 0.0, label: Annotated[str, TEXT] = "affine") -> None:
        self.ridge = ridge
        self.label = label
        self.keys: tuple[DataKey, ...] = ()
        self.names: tuple[str, ...] = ()
        self.weights = np.zeros((0, 0))

    def _stack(self, inputs: SurrogateInputs) -> NDArray[np.float64]:
        return np.concatenate([np.asarray(inputs[n], dtype=np.float64) for n in self.names])

    def fit(self, snapshots: SnapshotSet, rng: np.random.Generator) -> None:
        self.names = snapshots.layout.names
        self.keys = snapshots.keys
        design = np.vstack([self._stack(snapshots.inputs), np.ones((1, snapshots.n_runs))])
        solution, *_ = np.linalg.lstsq(design.T, snapshots.outputs.T, rcond=None)
        self.weights = np.ascontiguousarray(solution.T)

    def coordinates(
        self, inputs: SurrogateInputs
    ) -> tuple[NDArray[np.float64], NDArray[np.float64]]:
        stacked = self._stack(inputs)
        return stacked, np.zeros(stacked.shape[1])

    def predict(self, inputs: SurrogateInputs, keys: Sequence[DataKey]) -> NDArray[np.float64]:
        rows = [self.keys.index(k) for k in keys]
        stacked = self._stack(inputs)
        full = self.weights[:, :-1] @ stacked + self.weights[:, -1:]
        return np.ascontiguousarray(full[rows])

    def to_arrays(self) -> SurrogateParts:
        own = {"names": list(self.names), "keys": [[k.time, k.datatype] for k in self.keys],
               "ridge": self.ridge, "label": self.label}  # fmt: skip
        return own, {"weights": self.weights}

    @classmethod
    def from_arrays(
        cls, manifest: Mapping[str, object], arrays: Mapping[str, NDArray[np.generic]]
    ) -> Self:
        model = cls(ridge=float(manifest["ridge"]), label=str(manifest["label"]))  # type: ignore[arg-type]
        model.names = tuple(manifest["names"])  # type: ignore[arg-type]
        model.keys = tuple(DataKey(t, d) for t, d in manifest["keys"])  # type: ignore[attr-defined]
        model.weights = np.asarray(arrays["weights"], dtype=np.float64)
        return model


def _inputs(rng: np.random.Generator, n: int, scale: float = 1.0) -> dict[str, NDArray[np.float64]]:
    return {"a": scale * rng.uniform(-1, 1, (2, n)), "b": scale * rng.uniform(0, 1, (1, n))}


def _truth(inputs: Mapping[str, NDArray[np.float64]]) -> NDArray[np.float64]:
    return np.asarray(MATRIX @ np.vstack([inputs["a"], inputs["b"]]) + OFFSET[:, None])


def _snapshots(n: int, seed: int) -> SnapshotSet:
    inputs = _inputs(np.random.default_rng(seed), n)
    return SnapshotSet(
        layout=LAYOUT,
        inputs=inputs,
        keys=KEYS,
        outputs=_truth(inputs),
        run_ids=tuple(range(n)),
        provenance=SnapshotProvenance(simulator="linear", plan="lhs", seed=seed),
        failed=(n + 1,),
    )


