def test_arrays_never_hold_objects(tmp_path: Path) -> None:
    model, training, held_out = _fitted()
    domain = training_domain(model, training.inputs, held_out.inputs)

    class _Objects(_Affine):
        def to_arrays(self) -> SurrogateParts:
            own, arrays = super().to_arrays()
            return own, {**arrays, "code": np.array([print], dtype=object)}

    objects = _Objects()
    objects.__dict__.update(model.__dict__)
    with pytest.raises(ConfigError, match="never objects"):
        write_surrogate(tmp_path / "s.json", plugin="test_affine", model=objects, domain=domain,
                        provenance=training.provenance)  # fmt: skip

    # A pickled array slipped into the file is refused on reading, before anything runs.
    stored = write_surrogate(tmp_path / "s.json", plugin="test_affine", model=model,
                             domain=domain, provenance=training.provenance)  # fmt: skip
    import hashlib
    import io

    buffer = io.BytesIO()
    np.savez(buffer, weights=np.array([print], dtype=object))
    (tmp_path / "s.npz").write_bytes(buffer.getvalue())
    manifest = (tmp_path / "s.json").read_text()
    (tmp_path / "s.json").write_text(
        manifest.replace(
            stored.manifest.arrays.sha256, hashlib.sha256(buffer.getvalue()).hexdigest()
        )
    )
    with pytest.raises(ConfigError, match="cannot read"):
        read_surrogate(tmp_path / "s.json")


