def test_a_snapshot_set_checks_shapes_and_holds_read_only_contiguous_copies() -> None:
    inputs = {"a": np.asfortranarray(np.ones((2, 3))), "b": np.ones((1, 3))}
    snapshots = SnapshotSet(
        layout=LAYOUT, inputs=inputs, keys=KEYS, outputs=np.zeros((3, 3)),
        run_ids=(0, 1, 2), provenance=SnapshotProvenance(simulator="linear"),
    )  # fmt: skip

    assert snapshots.inputs["a"].flags.c_contiguous
    assert not snapshots.inputs["a"].flags.writeable
    inputs["a"][0, 0] = 5.0
    assert snapshots.inputs["a"][0, 0] == 1.0
    sub = snapshots.columns([2, 0])
    assert sub.run_ids == (2, 0)
    assert sub.outputs.flags.c_contiguous
    with pytest.raises(ValueError, match=r"must be \(3, 3\)"):
        SnapshotSet(layout=LAYOUT, inputs=inputs, keys=KEYS, outputs=np.zeros((3, 2)),
                    run_ids=(0, 1, 2), provenance=SnapshotProvenance(simulator="x"))  # fmt: skip
    with pytest.raises(ValueError, match="not finite"):
        SnapshotSet(layout=LAYOUT, inputs=inputs, keys=KEYS, outputs=np.full((3, 3), np.nan),
                    run_ids=(0, 1, 2), provenance=SnapshotProvenance(simulator="x"))  # fmt: skip
    with pytest.raises(ValueError, match="failed run"):
        SnapshotSet(layout=LAYOUT, inputs=inputs, keys=KEYS, outputs=np.zeros((3, 3)),
                    run_ids=(0, 1, 2), failed=(1,),
                    provenance=SnapshotProvenance(simulator="x"))  # fmt: skip


def test_the_snapshot_digest_follows_the_content() -> None:
    assert _snapshots(5, 1).digest() == _snapshots(5, 1).digest()
    assert _snapshots(5, 1).digest() != _snapshots(5, 2).digest()
    other = _snapshots(5, 1)
    changed = SnapshotSet(
        layout=other.layout, inputs=other.inputs, keys=other.keys, outputs=other.outputs,
        run_ids=other.run_ids, provenance=other.provenance.model_copy(update={"seed": 9}),
        failed=other.failed,
    )  # fmt: skip
    assert changed.digest() != other.digest()


