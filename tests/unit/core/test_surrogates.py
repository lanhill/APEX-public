def test_the_domain_is_built_from_the_models_coordinates_of_both_sets() -> None:
    model, training, held_out = _fitted()

    domain = training_domain(model, training.inputs, held_out.inputs)

    stacked = np.hstack([np.vstack([s.inputs["a"], s.inputs["b"]]) for s in (training, held_out)])
    np.testing.assert_array_equal(domain.lower, stacked.min(axis=1))
    np.testing.assert_array_equal(domain.upper, stacked.max(axis=1))
    assert domain.keys == KEYS
    assert domain.n_points == 30
    assert domain.time_range == ("0", "1")
    # An exact surrogate passes the gate on the held-out runs.
    result = gate(model.predict(held_out.inputs, KEYS), held_out.outputs, KEYS, held_out.run_ids,
                  variances=np.ones(3))  # fmt: skip
    assert result.passed
    assert max(d.error or 0.0 for d in result.datatypes) < 1e-10
    found = check_members(domain, model, _inputs(np.random.default_rng(5), 4, scale=3.0),
                          [0, 1, 2, 3], [KEYS[0], DataKey("2", "WOPR:P1")])  # fmt: skip
    assert found.members
    assert found.unknown_keys == (DataKey("2", "WOPR:P1"),)


# ------------------------------------------------------------- executors (validation 1)


class _Stand:
    """What a surrogate simulator does (test only is phase 3): check, predict."""

    def __init__(self, model: _Affine, domain: TrainingDomain) -> None:
        self.model = model
        self.domain = domain

    def run(self, member: MemberInput, keys: Sequence[DataKey]) -> NDArray[np.float64]:
        inputs = {k: np.asarray(v)[:, None] for k, v in member.state.items()}
        check_members(self.domain, self.model, inputs, [member.member_id], keys).raise_if_outside()
        return self.model.predict(inputs, keys)[:, 0]


def _members(inputs: Mapping[str, NDArray[np.float64]]) -> list[MemberInput]:
    n = inputs["a"].shape[1]
    return [MemberInput(i, {k: v[:, i] for k, v in inputs.items()}) for i in range(n)]


@pytest.mark.parametrize("executor", [SerialExecutor(), LocalProcessExecutor(workers=2)])
def test_a_member_outside_stops_the_forecast_and_is_never_a_dropped_member(
    executor: SerialExecutor | LocalProcessExecutor,
) -> None:
    model, training, held_out = _fitted()
    stand = _Stand(model, training_domain(model, training.inputs, held_out.inputs))
    inputs = _inputs(np.random.default_rng(8), 4, scale=0.5)
    inputs["a"][0, 2] = 7.0  # far outside [-1, 1]

    with pytest.raises(SurrogateDomainError, match="member 2") as raised:
        executor.run_all(stand, _members(inputs), list(KEYS))
    assert raised.value.members == (2,)


def test_serial_and_process_executors_predict_identically() -> None:
    model, training, held_out = _fitted()
    stand = _Stand(model, training_domain(model, training.inputs, held_out.inputs))
    members = _members(_inputs(np.random.default_rng(4), 6, scale=0.5))

    serial = SerialExecutor().run_all(stand, members, list(KEYS))
    process = LocalProcessExecutor(workers=3).run_all(stand, members, list(KEYS))

    assert not any(isinstance(r, MemberFailure) for r in serial + process)
    for a, b in zip(serial, process, strict=True):
        np.testing.assert_array_equal(a, b)
    # Deterministic and C-contiguous, even for inputs in Fortran order.
    batch = _inputs(np.random.default_rng(4), 6, scale=0.5)
    fortran = {k: np.asfortranarray(v) for k, v in batch.items()}
    predicted = model.predict(fortran, KEYS)
    assert predicted.flags.c_contiguous
    np.testing.assert_array_equal(predicted, model.predict(batch, KEYS))
    np.testing.assert_allclose(predicted, _truth(batch), rtol=1e-12, atol=1e-10)


# ---------------------------------------------------------------- files and loading


def _write(path: Path) -> tuple[_Affine, StoredSurrogate]:
    model, training, held_out = _fitted()
    domain = training_domain(model, training.inputs, held_out.inputs, extent="mahalanobis")
    result = gate(model.predict(held_out.inputs, KEYS), held_out.outputs, KEYS, held_out.run_ids,
                  variances=np.ones(3))  # fmt: skip
    stored = write_surrogate(
        path, plugin="test_affine", model=model, domain=domain,
        provenance=training.provenance, options={"ridge": 0.0, "label": "affine"}, gate=result,
        snapshots=SnapshotReference(path="snapshots.npz", digest=training.digest()),
        fit=FitRecord(seed=0, stream_state=dict(np.random.default_rng(0).bit_generator.state)),
        apex_commit="abc",
    )  # fmt: skip
    return model, stored


def test_a_surrogate_round_trips_through_its_files_to_identical_predictions(
    tmp_path: Path, registered: None
) -> None:
    from apex.services.surrogates import load_surrogate

    model, stored = _write(tmp_path / "model" / "surrogate.json")

    loaded = load_surrogate(tmp_path / "model" / "surrogate.json")

    assert loaded.identity == stored.identity
    assert loaded.manifest.plugin == "test_affine"
    assert loaded.manifest.plugin_version == "1"
    assert loaded.manifest.gate is not None
    assert loaded.manifest.gate.passed
    assert loaded.domain.to_document() == stored.manifest.training_domain().to_document()
    probe = _inputs(np.random.default_rng(11), 5, scale=0.5)
    np.testing.assert_array_equal(loaded.model.predict(probe, KEYS), model.predict(probe, KEYS))
    # Writing the same model again gives the same bytes, so the same identity.
    _, again = _write(tmp_path / "again" / "surrogate.json")
    assert again.identity == stored.identity
    assert load_surrogate(tmp_path / "model" / "surrogate.json", identity=loaded.identity)


def test_a_plugins_scalar_arrays_keep_their_shape_through_the_files(
    tmp_path: Path, registered: None, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A 0-d array is read back 0-d (it came back 1-d: flow_diagnostics' schema version)."""
    original = _Affine.to_arrays

    def with_scalars(self: _Affine) -> SurrogateParts:
        own, arrays = original(self)
        return own, {**arrays, "version": np.asarray(1, dtype=">i8"), "scale": np.asarray(2.5)}

    monkeypatch.setattr(_Affine, "to_arrays", with_scalars)
    path = tmp_path / "surrogate.json"
    _, stored = _write(path)
    read = read_surrogate(path)
    for arrays in (stored.arrays, read.arrays):
        assert (arrays["version"].shape, arrays["scale"].shape) == ((), ())
        assert int(arrays["version"]) == 1
        assert arrays["version"].dtype == np.dtype("<i8")
        assert arrays["weights"].ndim == 2


def test_any_changed_byte_changes_the_identity_and_is_refused(
    tmp_path: Path, registered: None
) -> None:
    path = tmp_path / "surrogate.json"
    _, stored = _write(path)
    manifest, arrays = path.read_bytes(), path.with_suffix(".npz").read_bytes()
    identity = identity_of(manifest, arrays)
    assert identity == stored.identity

    for i in range(len(manifest)):
        assert (
            identity_of(manifest[:i] + bytes([manifest[i] ^ 1]) + manifest[i + 1 :], arrays)
            != identity
        )
    for i in range(len(arrays)):
        assert (
            identity_of(manifest, arrays[:i] + bytes([arrays[i] ^ 1]) + arrays[i + 1 :]) != identity
        )

    # A changed arrays file is not the one the manifest records.
    changed = bytearray(arrays)
    changed[-1] ^= 1
    path.with_suffix(".npz").write_bytes(bytes(changed))
    with pytest.raises(ConfigError, match="not the ones its manifest"):
        read_surrogate(path)
    # A changed manifest is another identity than the one recorded.
    path.with_suffix(".npz").write_bytes(arrays)
    path.write_bytes(manifest.replace(b'"apex_commit": "abc"', b'"apex_commit": "abd"'))
    with pytest.raises(ConfigError, match="model file changed"):
        read_surrogate(path, identity=identity)


def test_manifests_naming_unknown_plugins_options_or_other_files_are_refused(
    tmp_path: Path, registered: None
) -> None:
    from apex.services.surrogates import load_surrogate

    path = tmp_path / "surrogate.json"
    _write(path)
    original = json.loads(path.read_text())

    def edited(**changes: object) -> Path:
        document = json.loads(json.dumps(original))
        for trail, value in changes.items():
            *parents, last = trail.split("__")
            target = document
            for parent in parents:
                target = target[parent]
            target[last] = value
        path.write_text(json.dumps(document))
        return path

    with pytest.raises(UnknownPluginError, match="'nope'"):
        load_surrogate(edited(plugin="nope"))
    with pytest.raises(ConfigError, match="does not take"):
        load_surrogate(edited(options={"lable": "affine"}))
    with pytest.raises(ConfigError, match=r"only a \.npz file beside it"):
        read_surrogate(edited(arrays__file="../surrogate.npz"))
    with pytest.raises(ConfigError, match="not valid"):
        read_surrogate(edited(format=2))
    with pytest.raises(ConfigError, match="not valid"):
        read_surrogate(edited(unexpected=1))


def test_byte_order_does_not_change_the_identity(tmp_path: Path) -> None:
    model, training, held_out = _fitted()
    domain = training_domain(model, training.inputs, held_out.inputs)
    little = write_surrogate(tmp_path / "le.json", plugin="test_affine", model=model,
                             domain=domain, provenance=training.provenance)  # fmt: skip
    model.weights = model.weights.astype(">f8")
    big = write_surrogate(tmp_path / "be.json", plugin="test_affine", model=model,
                          domain=domain, provenance=training.provenance)  # fmt: skip
    # The manifests differ only by the arrays file's name: compare the arrays and identities
    # of files written under one name.
    assert (tmp_path / "le.npz").read_bytes() == (tmp_path / "be.npz").read_bytes()
    assert little.manifest.arrays.sha256 == big.manifest.arrays.sha256
    model.weights = model.weights.astype("<f8")
    again = write_surrogate(tmp_path / "be.json", plugin="test_affine", model=model,
                            domain=domain, provenance=training.provenance)  # fmt: skip
    assert again.identity == big.identity


